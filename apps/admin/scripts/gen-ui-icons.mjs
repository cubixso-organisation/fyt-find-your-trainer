// Generates src/components/icons/ui-icon-data.ts from the Icons8 interface
// marks vendored in scripts/ui-icons/ (ported from the NutriGreenz icon
// system, where they were traced from the Icons8 iOS set to a single path).
// Inlined so they tint with currentColor and need no network request.
// Icons by Icons8 (https://icons8.com); credited on /credits and in NOTICE.md.
// Run: node scripts/gen-ui-icons.mjs   (re-run after adding an SVG + name)
import { readFileSync, writeFileSync } from "node:fs";

export const NAMES = ["search", "export", "audit", "verified", "certificate"];

// Traced coordinates carry two decimals on a 400-1200 unit grid; one is
// already far below a device pixel at the 16-20px these draw at.
const round = (d) => d.replace(/-?\d*\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

const entries = NAMES.map((name) => {
  const svg = readFileSync(new URL(`./ui-icons/${name}.svg`, import.meta.url), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => round(m[1]));
  if (!viewBox || paths.length !== 1) {
    console.error(`${name}.svg: expected one <path> and a viewBox`);
    process.exit(1);
  }
  return `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(viewBox)}, d: ${JSON.stringify(paths[0])} },`;
});

writeFileSync(
  "src/components/icons/ui-icon-data.ts",
  `// AUTO-GENERATED by scripts/gen-ui-icons.mjs from scripts/ui-icons/*.svg. Do not edit.
// Icons by Icons8 (https://icons8.com), traced to vector and recoloured.
export const UI_ICONS = {
${entries.join("\n")}
} as const;
export type UiIconName = keyof typeof UI_ICONS;
`,
);
console.log(`Wrote ${NAMES.length} UI icons`);
